let current = 'en';
export function setLang(lang) { current = STRINGS[lang] ? lang : 'en'; }
export function getLang() { return current; }

/** Number-aware text: picks "key.one", "key.two", "key.few"… by the language's plural rules. */
export function tn(key, n, vars) {
  let cat = 'other';
  try { cat = new Intl.PluralRules(current).select(n); } catch { cat = n === 1 ? 'one' : 'other'; }
  const k = `${key}.${cat}`;
  return t(STRINGS[current][k] != null ? k : key, { n, ...vars });
}

/** Looks up a key and fills {placeholders}. Falls back to English, then to the key itself. */
export function t(key, vars) {
  let s = STRINGS[current][key];
  if (s == null) s = STRINGS.en[key];
  if (s == null) return key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
  return s;
}
